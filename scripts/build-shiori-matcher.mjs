import { build } from "esbuild";
import { createHash } from "node:crypto";
import { writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
const result = await build({
    entryPoints: ["src/services/lyrics-matching.ts"],
    bundle: true,
    format: "iife",
    globalName: "FullscapeMatcher",
    target: "es2020",
    minify: true,
    write: false,
});
const js = result.outputFiles[0].text;
const version = createHash("sha256").update(js).digest("hex");
const generated = `// Generated by scripts/build-shiori-matcher.mjs\nexport const MATCHER_VERSION = "${version}";\n`;
if (process.argv[2] === "--check") {
    if (readFileSync("src/services/lyrics-matcher-version.ts", "utf8") !== generated)
        throw new Error(
            "Matcher bundle is stale: regenerate both repositories with the Shiori Resources path",
        );
} else {
    writeFileSync("src/services/lyrics-matcher-version.ts", generated);
    if (process.argv[2]) {
        const out = resolve(process.argv[2]);
        mkdirSync(out, { recursive: true });
        writeFileSync(resolve(out, "fullscape-matcher.js"), js);
        writeFileSync(resolve(out, "fullscape-matcher-version.txt"), version);
        writeFileSync(
            resolve(out, "fullscape-matcher-license.txt"),
            readFileSync("node_modules/opencc-js/LICENSE", "utf8"),
        );
    }
}
console.log(`Matcher ${version}`);
